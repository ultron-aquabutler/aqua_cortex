#!/usr/bin/env python3
"""hermes aqua-cortex — terminal surface for the aqua_cortex RAG index.

Subcommands
-----------
  hermes aqua-cortex query "free-text question"
      Hybrid search (lexical + vector) on the Meilisearch index, send the
      top chunks to the existing llama.cpp /v1/chat/completions endpoint,
      and print a citation-bearing answer.

  hermes aqua-cortex snapshot
      Emit a static JSON snapshot of the joined index — the same payload the
      Grafana "aqua_cortex" panel pulls. Useful for local sanity checks
      and as a cron target that the panel import flow can rely on without
      a long-running cortex API server.

  hermes aqua-cortex ping
      Sanity check: print whether the configured Meilisearch index exists
      and has any documents, plus whether the llama.cpp /v1/embeddings
      endpoint responds. Exits non-zero on any failure.

Design choices
--------------
* No long-running cortex API service is required for v1. The CLI talks
  directly to Meilisearch + llama.cpp over HTTPS — both already on the
  home swarm, both reachable from the operator's terminal and from inside
  Swarm containers.

* Citations are parsed out of the chunk metadata, not generated by the
  LLM. The system prompt instructs the model to answer using ONLY the
  provided chunks; we then prepend the citations deterministically. This
  keeps hallucinated sources out of the output even when the model drifts.

* Configuration is read from the repo's `aqua_cortex.toml` (same source
  of truth as the indexer) so a single edit covers indexer + CLI + panel.
  CLI-specific overrides come from env vars (HERMES_AQUA_CORTEX_*).

Cluster isolation
-----------------
* Reads only. No writes to Meilisearch, no writes to Obsidian, no writes
  to the kanban DB, no writes to the Aqua swarm.
* The CLI runs on the operator's terminal (or anywhere with HTTPS to
  meili.loc.wallacearizona.us + llama.loc.wallacearizona.us). It does NOT
  deploy as a Swarm service in v1.
"""

from __future__ import annotations

