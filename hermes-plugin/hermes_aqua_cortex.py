def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="hermes aqua-cortex",
        description="Terminal surface for the aqua_cortex RAG index.",
    )
    sub = p.add_subparsers(dest="cmd", required=True)

    p_query = sub.add_parser("query", help="Ask a question; print answer + sources")
    p_query.add_argument("question", help="Free-text question")
    p_query.add_argument("--top-k", type=int, default=None,
                         help="Override HERMES_AQUA_CORTEX_TOP_K (default 5)")
    p_query.add_argument("--max-tokens", type=int, default=512,
                         help="Max tokens for the answer (default 512)")
    p_query.set_defaults(func=cmd_query)
    p_snap = sub.add_parser("snapshot", help="Emit Grafana-datasource JSON snapshot")
    p_snap.set_defaults(func=cmd_snapshot)

    p_ping = sub.add_parser("ping", help="Sanity check Meilisearch + llama.cpp")
    p_ping.set_defaults(func=cmd_ping)

    return p


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s %(message)s",
    )
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
