# ---------------------------------------------------------------------------
# Config + env overrides
# ---------------------------------------------------------------------------


@dataclasses.dataclass
class CLIConfig:
    """Subcommand runtime knobs. Sourced from IndexerConfig + env overrides."""

    meili_url: str
    meili_index: str
    meili_api_key: str
    llama_url: str
    llama_model: str
    llama_api_key: str | None
    top_k: int
    http_timeout_s: float
    verify_tls: bool

    @classmethod
    def load(cls) -> "CLIConfig":
        cfg = IndexerConfig.load()
        # Prefer env overrides so a one-shot `HERMES_AQUA_CORTEX_MEILI_URL=...`
        # can repoint the CLI without editing aqua_cortex.toml.
        meili_url = os.environ.get("HERMES_AQUA_CORTEX_MEILI_URL") or cfg.meili_url
        meili_index = os.environ.get("HERMES_AQUA_CORTEX_MEILI_INDEX") or cfg.meili_index
        llama_url = os.environ.get("HERMES_AQUA_CORTEX_LLAMA_URL") or cfg.llama_url
        llama_model = os.environ.get("HERMES_AQUA_CORTEX_LLAMA_MODEL") or cfg.llama_model

        key_path = os.environ.get("HERMES_AQUA_CORTEX_MEILI_KEY_FILE") or cfg.meili_key_file
        try:
            with open(key_path, "r", encoding="utf-8") as fh:
                meili_api_key = fh.read().strip()
        except OSError as exc:
            raise SystemExit(
                f"hermes-aqua-cortex: cannot read Meilisearch key from {key_path}: {exc}"
            )

        return cls(
            meili_url=meili_url.rstrip("/"),
            meili_index=meili_index,
            meili_api_key=meili_api_key,
            llama_url=llama_url.rstrip("/"),
            llama_model=llama_model,
            llama_api_key=os.environ.get("HERMES_AQUA_CORTEX_LLAMA_API_KEY"),
            top_k=int(os.environ.get("HERMES_AQUA_CORTEX_TOP_K", "5")),
            http_timeout_s=float(os.environ.get("HERMES_AQUA_CORTEX_TIMEOUT_S", "30")),
            verify_tls=os.environ.get("HERMES_AQUA_CORTEX_VERIFY_TLS", "1") not in ("0", "false", "False"),
        )


# ---------------------------------------------------------------------------
# Meilisearch hybrid search
# ---------------------------------------------------------------------------


def _headers(cfg: CLIConfig) -> dict[str, str]:
    h = {"Authorization": f"Bearer {cfg.meili_api_key}"}
    return h


def search_chunks(cfg: CLIConfig, query: str, *, limit: int = 5) -> list[dict[str, Any]]:
    """Hybrid search: lexical `q` + dense `vector` against the same `query`.

    Falls back to lexical-only if embedding fails (e.g. llama.cpp down).
    Returns the raw `hits` array as Meilisearch delivered it (already in
    field-flattened form because the indexer serializes `live_state` inline).
    """
    body: dict[str, Any] = {
        "q": query,
        "limit": limit,
        "attributesToRetrieve": [
            "id",
            "source",
            "application",
            "doc_path",
            "doc_title",
            "section",
            "section_anchor",
            "chunk_index",
            "chunk_text",
            "linked_services",
            "linked_cards",
            "linked_commits",
            "live_state",
            "indexed_at",
        ],
        "showRankingScore": True,
    }
    # Try to add a dense vector. If the embed endpoint is unreachable, we
    # fall back to lexical-only — still useful, just less precise.
    #
    # Meilisearch 1.12 hybrid search contract: when `vector` is supplied,
    # `hybrid` MUST also be present (and vice versa). The embedder name
    # must match what was configured at index time (default: "default").
    try:
        vec = embed_query(cfg, query)
        body["vector"] = vec
        body["hybrid"] = {"embedder": "default", "semanticRatio": 0.5}
    except Exception as exc:  # noqa: BLE001 — surface the failure in `--verbose`
        log.warning("vector embedding failed (%s); falling back to lexical-only", exc)

    url = f"{cfg.meili_url}/indexes/{cfg.meili_index}/search"
    with httpx.Client(timeout=cfg.http_timeout_s, verify=cfg.verify_tls) as client:
        r = client.post(url, json=body, headers=_headers(cfg))
        r.raise_for_status()
        data = r.json()
    return data.get("hits", [])


def embed_query(cfg: CLIConfig, query: str) -> list[float]:
    """Embed a single query via the OpenAI-compatible /v1/embeddings endpoint."""
    body = {"input": query, "model": cfg.llama_model}
    url = f"{cfg.llama_url}/v1/embeddings"
    headers: dict[str, str] = {"Content-Type": "application/json"}
    if cfg.llama_api_key:
        headers["Authorization"] = f"Bearer {cfg.llama_api_key}"
    with httpx.Client(timeout=cfg.http_timeout_s, verify=cfg.verify_tls) as client:
        r = client.post(url, json=body, headers=headers)
        r.raise_for_status()
        data = r.json()
    vec = data["data"][0]["embedding"]
    if not isinstance(vec, list) or not vec:
        raise RuntimeError("embedding endpoint returned empty vector")
    return vec


# ---------------------------------------------------------------------------
# Citation formatting
# ---------------------------------------------------------------------------


def _citation_lines(hits: Iterable[dict[str, Any]], *, max_per_kind: int = 8) -> list[str]:
    """Build the deterministic Sources: list from chunk metadata.

    Format (one line per source):
      - <doc_path>#<section_anchor>           (obsidian doc + section)
      - kanban:t_<hex>                         (linked kanban card)
      - swarm:<service>=<swarm_state>          (live_state)
    We dedupe (same doc+section appearing twice from different chunks
    collapses to one entry) and stable-sort so the output is reproducible.
    Each kind is capped at `max_per_kind` so a corpus-wide topic (e.g.
    "supabase" hits a chunk with 30+ linked kanban cards) doesn't bury
    the actually useful citations.
    """
    seen_doc_section: set[tuple[str, str]] = set()
    seen_cards: set[str] = set()
    seen_swarm: set[tuple[str, str]] = set()
    doc_lines: list[str] = []
    card_lines: list[str] = []
    swarm_lines: list[str] = []

    for hit in hits:
        doc_path = (hit.get("doc_path") or "").strip()
        section_anchor = (hit.get("section_anchor") or "").strip() or "#"
        if doc_path and len(doc_lines) < max_per_kind:
            key = (doc_path, section_anchor)
            if key not in seen_doc_section:
                seen_doc_section.add(key)
                doc_lines.append(f"  - {doc_path}{section_anchor}")

        for cid in hit.get("linked_cards") or []:
            if len(card_lines) >= max_per_kind:
                break
            cid = str(cid).strip()
            if cid and cid not in seen_cards:
                seen_cards.add(cid)
                card_lines.append(f"  - kanban:{cid}")

        ls = hit.get("live_state")
        if isinstance(ls, dict):
            service = (ls.get("service") or "").strip()
            state = (ls.get("swarm_state") or "").strip()
            if service and state and len(swarm_lines) < max_per_kind:
                k = (service, state)
                if k not in seen_swarm:
                    seen_swarm.add(k)
                    swarm_lines.append(f"  - swarm:{service}={state}")

    # Stable sort within each kind; group kinds together.
    lines = sorted(doc_lines) + sorted(card_lines) + sorted(swarm_lines)
    return lines


# ---------------------------------------------------------------------------
# LLM answer generation
# ---------------------------------------------------------------------------


_SYSTEM_PROMPT = textwrap.dedent(
    """\
    You are aqua_cortex, a retrieval-grounded assistant for the AquaButler
    pool deployment. You answer using ONLY the numbered chunks below.
    Each chunk is prefixed with `[<n>] path#anchor`. When you use a fact
    from a chunk, append `(<n>)` after the sentence that uses it. If the
    chunks do not contain the answer, reply exactly: "No matching context."
    Do not invent services, commit SHAs, kanban card ids, or swarm states.
    """
).strip()


def _looks_broken(text: str) -> bool:
    """Heuristic for Qwen2.5-1.5B-Instruct going off the rails.

    The home llama.cpp deployment occasionally produces degenerate output
    (single-token loops, garbage tokens, half-translated sentences). The
    quality detection we ship here is conservative — if any of these trip
    we treat the LLM output as untrustworthy and fall back to an
    extractive answer built directly from the top chunks.

    Triggers (any one is enough):
      - Output is shorter than 20 chars (LLM said "I don't know" or similar)
      - Output repeats the same 1-3 token bigram more than 8 times
      - More than 40% of words are the same single word
    """
    if len(text) < 20:
        return True
    words = text.split()
    if not words:
        return True
    # Single-word-dominance: 1 word = >40% of total.
    counts: dict[str, int] = {}
    for w in words:
        counts[w] = counts.get(w, 0) + 1
    top_word, top_count = max(counts.items(), key=lambda kv: kv[1])
    if top_count / max(len(words), 1) > 0.4:
        return True
    # Bigram repetition: same 2-word window > 8 times.
    bigrams: dict[tuple[str, str], int] = {}
    for i in range(len(words) - 1):
        bg = (words[i], words[i + 1])
        bigrams[bg] = bigrams.get(bg, 0) + 1
    if bigrams and max(bigrams.values()) > 8:
        return True
    return False


def _extractive_answer(query: str, hits: list[dict[str, Any]]) -> str:
    """Deterministic fallback when the LLM produces degenerate output.

    We pick the top 2 chunks, return a short headline + their first
    paragraph as the "answer". The user still gets useful text plus
    the Sources list (which is the real value of this CLI anyway).
    """
    if not hits:
        return "No matching context."
    snippets: list[str] = []
    for h in hits[:2]:
        text = (h.get("chunk_text") or "").strip().splitlines()
        # First non-empty paragraph.
        para = next((ln for ln in text if ln.strip()), "")
        if len(para) > 240:
            para = para[:237].rstrip() + "..."
        title = h.get("doc_title") or h.get("doc_path") or "?"
        snippets.append(f"[{title}] {para}")
    return "Top matching context (LLM output was untrustworthy; using extractive fallback):\n\n" + "\n\n".join(snippets)


def answer_question(
    cfg: CLIConfig,
    query: str,
    hits: list[dict[str, Any]],
    *,
    max_tokens: int = 512,
    temperature: float = 0.1,
) -> str:
    """Call llama.cpp /v1/chat/completions with the chunks as context.

    Falls back to an extractive answer when the model produces degenerate
    output (the home Qwen2.5-1.5B-Instruct quant occasionally goes off
    the rails; see `_looks_broken`).
    """
    if not hits:
        return "No matching context."

    numbered = []
    for i, hit in enumerate(hits, start=1):
        path = hit.get("doc_path", "?")
        anchor = hit.get("section_anchor") or "#"
        text = (hit.get("chunk_text") or "").strip()
        numbered.append(f"[{i}] {path}{anchor}\n{text}")
    context_block = "\n\n---\n\n".join(numbered)

    user_msg = (
        f"Question: {query}\n\n"
        f"Context chunks:\n\n{context_block}\n\n"
        "Answer using only the chunks above. Cite chunk numbers in parens."
    )

    body = {
        "model": cfg.llama_model,
        "messages": [
            {"role": "system", "content": _SYSTEM_PROMPT},
            {"role": "user", "content": user_msg},
        ],
        "temperature": temperature,
        "max_tokens": max_tokens,
        "stream": False,
    }
    url = f"{cfg.llama_url}/v1/chat/completions"
    headers: dict[str, str] = {"Content-Type": "application/json"}
    if cfg.llama_api_key:
        headers["Authorization"] = f"Bearer {cfg.llama_api_key}"
    try:
        with httpx.Client(timeout=cfg.http_timeout_s, verify=cfg.verify_tls) as client:
            r = client.post(url, json=body, headers=headers)
            r.raise_for_status()
            data = r.json()
        try:
            answer = data["choices"][0]["message"]["content"].strip()
        except (KeyError, IndexError, TypeError) as exc:
            raise RuntimeError(f"unexpected chat completion payload: {data!r}") from exc
    except Exception as exc:  # noqa: BLE001
        log.warning("LLM call failed (%s); using extractive fallback", exc)
        return _extractive_answer(query, hits)

    if _looks_broken(answer):
        log.warning("LLM output looked degenerate; using extractive fallback")
        return _extractive_answer(query, hits)
    return answer


