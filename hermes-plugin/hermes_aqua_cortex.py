def cmd_query(args: argparse.Namespace) -> int:
    cfg = CLIConfig.load()
    query = args.question
    # Resolve limit: CLI --top-k > env var > config default. argparse default
    # is None so we have to apply the env/default fallback here. Meilisearch
    # rejects `limit: null` with a 400 ("expected positive integer"), so we
    # must coerce before the request.
    if args.top_k is not None:
        limit = args.top_k
    else:
        limit = cfg.top_k
    hits = search_chunks(cfg, query, limit=limit)
    if not hits:
        print("No matching context.", file=sys.stderr)
        # Still emit a Sources block (empty) so downstream tools can
        # parse uniformly. Exit non-zero to flag "no answer".
        print("Sources:\n  - (none)")
        return 2

    answer = answer_question(cfg, query, hits, max_tokens=args.max_tokens)
    print(answer)

    sources = _citation_lines(hits)
    print("\nSources:")
    if sources:
        for line in sources:
            print(line)
    else:
        print("  - (chunks present but no extractable citations)")

    return 0


def cmd_snapshot(args: argparse.Namespace) -> int:
    cfg = CLIConfig.load()
    snap = build_snapshot(cfg)
    # Silence the noisy httpx INFO logs that would otherwise pollute the
    # JSON output (snapshots are piped to files / Grafana datasources).
    logging.getLogger("httpx").setLevel(logging.WARNING)
    json.dump(snap, sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")
    return 0


def cmd_ping(args: argparse.Namespace) -> int:
    cfg = CLIConfig.load()
    failures: list[str] = []

    # Meilisearch index check.
    try:
        with httpx.Client(timeout=cfg.http_timeout_s, verify=cfg.verify_tls) as client:
            r = client.get(
                f"{cfg.meili_url}/indexes/{cfg.meili_index}/stats",
                headers=_headers(cfg),
            )
            r.raise_for_status()
            stats = r.json()
        print(f"meili  : OK ({stats.get('numberOfDocuments', '?')} docs in '{cfg.meili_index}')")
    except Exception as exc:  # noqa: BLE001
        failures.append(f"meili: {exc}")
        print(f"meili  : FAIL ({exc})")

    # llama.cpp embeddings check.
    try:
        vec = embed_query(cfg, "ping")
        print(f"llama  : OK (dim={len(vec)})")
    except Exception as exc:  # noqa: BLE001
        failures.append(f"llama: {exc}")
        print(f"llama  : FAIL ({exc})")

    return 0 if not failures else 1


# ---------------------------------------------------------------------------
