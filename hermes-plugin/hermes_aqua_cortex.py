def _doc_to_snapshot(doc: dict[str, Any]) -> dict[str, Any]:
    """Flatten one Meilisearch hit into the Grafana-friendly snapshot shape.

    The Grafana JSON datasource renders rows from this; the field names
    become column keys. Keep this stable — Grafana panels bind to it.
    """
    ls = doc.get("live_state") or {}
    return {
        "service": (ls.get("service") if isinstance(ls, dict) else None) or "",
        "documented": bool(doc.get("doc_path")),
        "running": isinstance(ls, dict) and bool(ls.get("service")),
        "swarm_state": (ls.get("swarm_state") if isinstance(ls, dict) else None) or "",
        "stack": (ls.get("stack") if isinstance(ls, dict) else None) or "",
        "node": (ls.get("node") if isinstance(ls, dict) else None) or "",
        "doc_path": doc.get("doc_path", ""),
        "doc_title": doc.get("doc_title", ""),
        "section": doc.get("section") or "",
        "section_anchor": doc.get("section_anchor") or "",
        "oldest_doc_indexed_at": doc.get("indexed_at", ""),
        "last_compose_change": "",  # populated by snapshot linker (git_state join)
        "source": doc.get("source", ""),
        "linked_cards": doc.get("linked_cards") or [],
        "linked_commits": doc.get("linked_commits") or [],
        "linked_services": doc.get("linked_services") or [],
        "checked_at": (ls.get("checked_at") if isinstance(ls, dict) else "") or "",
    }


def _list_all_documents(cfg: CLIConfig, *, page_size: int = 1000) -> list[dict[str, Any]]:
    """Walk the full index via paginated /documents listing.

    Meilisearch 1.x supports GET /indexes/{uid}/documents?limit=&offset=.
    For the cortex corpus (~500 docs) one or two pages is plenty.
    """
    url = f"{cfg.meili_url}/indexes/{cfg.meili_index}/documents"
    headers = _headers(cfg)
    out: list[dict[str, Any]] = []
    offset = 0
    while True:
        with httpx.Client(timeout=cfg.http_timeout_s, verify=cfg.verify_tls) as client:
            r = client.get(url, params={"limit": page_size, "offset": offset}, headers=headers)
            r.raise_for_status()
            data = r.json()
        results = data.get("results", [])
        if not results:
            break
        out.extend(results)
        if len(results) < page_size:
            break
        offset += page_size
        if offset > 20000:  # hard cap; cortex corpus is much smaller
            break
    return out


def build_snapshot(cfg: CLIConfig) -> dict[str, Any]:
    """Build the Grafana-datasource-shaped snapshot of the joined index."""
    raw = _list_all_documents(cfg)
    docs = [_doc_to_snapshot(d) for d in raw]

    # "Recent activity" — last 50 indexed, regardless of doc_path duplication.
    recent = sorted(
        ({"when": d.get("oldest_doc_indexed_at", ""),
          "source": d.get("source", ""),
          "summary": (d.get("doc_title") or d.get("doc_path") or ""),
          "service": d.get("service", ""),
          "doc_path": d.get("doc_path", "")} for d in docs),
        key=lambda r: r.get("when") or "",
        reverse=True,
    )[:50]

    # Doc freshness view — distinct (doc_path, doc_title).
    seen_paths: set[str] = set()
    freshness: list[dict[str, Any]] = []
    for d in docs:
        path = d.get("doc_path")
        if not path or path in seen_paths:
            continue
        seen_paths.add(path)
        freshness.append({
            "service": d.get("service", "") or path,
            "doc_path": path,
            "doc_title": d.get("doc_title", ""),
            "oldest_doc_indexed_at": d.get("oldest_doc_indexed_at", ""),
            "last_compose_change": d.get("last_compose_change", ""),
        })

    # Doc-vs-running view — distinct services.
    seen_svcs: dict[str, dict[str, Any]] = {}
    for d in docs:
        svc = d.get("service") or d.get("doc_path") or ""
        if not svc or svc in seen_svcs:
            continue
        seen_svcs[svc] = d
    doc_vs_running = sorted(
        (
            {
                "service": svc,
                "documented": bool(d.get("doc_path")),
                "running": bool(d.get("running")),
                "swarm_state": d.get("swarm_state", ""),
                "stack": d.get("stack", ""),
            }
            for svc, d in seen_svcs.items()
        ),
        key=lambda r: (r["running"], r["documented"], r["service"]),
    )

    return {
        "generated_at": _now_iso(),
        "index": cfg.meili_index,
        "counts": {
            "documents": len(docs),
            "distinct_services": len(seen_svcs),
            "distinct_doc_paths": len(seen_paths),
        },
        "doc_vs_running": doc_vs_running,
        "doc_freshness": freshness,
        "recent_activity": recent,
    }


def _now_iso() -> str:
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


